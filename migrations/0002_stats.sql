-- Anonymised scores kept after a session is deleted or expires. No names, tokens or IPs.
CREATE TABLE stats (
  id INTEGER PRIMARY KEY AUTOINCREMENT,
  day TEXT NOT NULL,
  a_c INTEGER NOT NULL, a_r INTEGER NOT NULL, a_i INTEGER NOT NULL, a_s INTEGER NOT NULL,
  a_pc INTEGER NOT NULL, a_pr INTEGER NOT NULL, a_pi INTEGER NOT NULL, a_ps INTEGER NOT NULL,
  b_c INTEGER NOT NULL, b_r INTEGER NOT NULL, b_i INTEGER NOT NULL, b_s INTEGER NOT NULL,
  b_pc INTEGER NOT NULL, b_pr INTEGER NOT NULL, b_pi INTEGER NOT NULL, b_ps INTEGER NOT NULL,
  a_t REAL NOT NULL, a_pt REAL NOT NULL, b_t REAL NOT NULL, b_pt REAL NOT NULL
);
